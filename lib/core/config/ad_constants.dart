/// 廣告相關常數配置
///
/// 集中管理所有廣告相關的時間、間隔、重試等參數，
/// 便於調整策略和進行 A/B 測試
class AdConstants {
  AdConstants._(); // 私有建構子，防止實例化

  // ============================================================
  // Interstitial 廣告（插頁式廣告）
  // ============================================================

  /// 插頁式廣告冷卻時間
  ///
  /// 兩次插頁式廣告之間的最小間隔時間，防止過度打擾用戶
  static const Duration interstitialCooldown = Duration(minutes: 5);

  /// 插頁式廣告載入重試延遲序列
  ///
  /// 當廣告載入失敗時，使用指數退避策略重試
  /// 例如：第1次失敗後等待2秒，第2次失敗後等待4秒，第3次失敗後等待8秒
  static const List<Duration> interstitialRetryDelays = [
    Duration(seconds: 2),
    Duration(seconds: 4),
    Duration(seconds: 8),
  ];

  // ============================================================
  // Banner 廣告（橫幅廣告）
  // ============================================================

  /// 橫幅廣告免除時長
  ///
  /// 用戶觀看獎勵廣告後，可獲得此時長的橫幅廣告免除
  static const Duration bannerAdFreeDuration = Duration(hours: 12);

  // ============================================================
  // App Open 廣告（應用開啟廣告）
  // ============================================================

  /// App Open 廣告快取有效期
  ///
  /// 超過此時間的預載廣告將被視為過期，需要重新載入
  static const Duration appOpenCacheDuration = Duration(hours: 4);

  // ============================================================
  // Native 廣告（原生廣告）
  // ============================================================

  /// 原生廣告在列表中的插入間隔
  ///
  /// 每隔多少條記錄插入一個原生廣告
  /// 例如：8 表示每 8 條記錄後插入 1 個廣告
  static const int nativeAdInterval = 8;

  // ============================================================
  // Rewarded 廣告（獎勵廣告）
  // ============================================================

  /// 獎勵廣告：廣告票券獎勵數量
  ///
  /// 用戶觀看一次獎勵廣告可獲得的票券數量
  static const int adTicketRewardAmount = 1;
}
